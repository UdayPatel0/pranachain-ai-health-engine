// Checks that patient explanations are SAFE and EASY TO READ, for every patient in web/data.
// Owner: Nancy · built with AI assistance (Claude), reviewed by the team.
//
//   node web/tests/check_explanations.mjs                       # check the rule-based preview for all patients
//   node web/tests/check_explanations.mjs --ai ai_outputs.json  # check AI answers: [{"id":"PC0001","text":"..."}]
//   add --report docs/testing/readability-report.md to write a Markdown report
//
// Pass rules (same as the panel): grade level <= 8, <= 20 words per sentence, no unexplained medical words,
// numbers match the evidence, no diagnosis / medicine-change words, disclaimer present.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildEvidence, previewExplanation, explanationText, safetyCheck, readability, READ_TARGET } from "../explain.js";

const here = dirname(fileURLToPath(import.meta.url));
const dataDir = resolve(here, "../data/chunks");
const arg = (k) => { const i = process.argv.indexOf(k); return i > -1 ? process.argv[i + 1] : null; };
const aiFile = arg("--ai"), reportPath = arg("--report");

const patients = readdirSync(dataDir).filter((f) => f.endsWith(".json")).sort()
  .flatMap((f) => JSON.parse(readFileSync(join(dataDir, f), "utf8")));
const aiText = aiFile ? Object.fromEntries(JSON.parse(readFileSync(aiFile, "utf8")).map((r) => [r.id, r.text])) : null;

const rows = [];
for (const p of patients) {
  const ev = buildEvidence(p);
  if (aiText && !(p.id in aiText)) continue;
  const text = aiText ? aiText[p.id] : explanationText(previewExplanation(ev));
  const s = safetyCheck(text, ev), r = readability(text);
  rows.push({ id: p.id, s, r, text });
}

const n = rows.length, pct = (k) => `${Math.round((k / n) * 100)}%`;
const grades = rows.map((x) => x.r.grade).sort((a, b) => a - b);
const median = grades[Math.floor(n / 2)];
const p90 = grades[Math.floor(n * 0.9)];
const safeFail = rows.filter((x) => !x.s.pass);
const readFail = rows.filter((x) => !x.r.pass);
const jargonCount = {};
rows.forEach((x) => x.r.jargon.forEach((j) => (jargonCount[j.term] = (jargonCount[j.term] || 0) + 1)));
const failBy = (id) => rows.filter((x) => !x.s.checks.find((c) => c.id === id).pass).length;

const summary = [
  `Checked ${n} explanations (${aiText ? "AI answers from " + aiFile : "rule-based preview"})`,
  `Safety: ${n - safeFail.length}/${n} pass (${pct(n - safeFail.length)}) · numbers fail ${failBy("numbers")} · words fail ${failBy("words")} · disclaimer fail ${failBy("disclaimer")}`,
  `Readability: ${n - readFail.length}/${n} pass (${pct(n - readFail.length)}) · median grade ${median} · 90th percentile grade ${p90} · target <= ${READ_TARGET.grade}`,
  `Unexplained medical words: ${Object.entries(jargonCount).map(([k, v]) => `${k} (${v})`).join(", ") || "none"}`,
];
console.log(summary.join("\n"));

if (reportPath) {
  const worst = [...rows].sort((a, b) => b.r.grade - a.r.grade).slice(0, 5);
  const sample = rows.find((x) => x.id === "PC0989") || rows[0];
  const md = `# Readability and safety check of patient explanations

Generated by \`node web/tests/check_explanations.mjs${aiFile ? " --ai " + aiFile : ""}\` on ${new Date().toISOString().slice(0, 10)}.

## Rules

| Check | Rule | Why |
|---|---|---|
| Reading level | Flesch–Kincaid grade ≤ ${READ_TARGET.grade} (ideal ≤ ${READ_TARGET.ideal}) | NIH and AMA advise patient materials at about a grade 6–8 reading level |
| Sentence length | ≤ ${READ_TARGET.wordsPerSentence} words per sentence on average | Short sentences are easier on a phone and for people reading in a second language |
| Medical words | No medical word without a plain name, e.g. "average blood sugar (HbA1c)" | Patients can match the bracketed word to their lab report |
| Numbers | Every number is in the evidence summary | The AI must not invent values |
| Words | No diagnosis or medicine-change words | VitaLens never diagnoses or gives dosing advice |
| Disclaimer | "This is not a diagnosis…" and mentions doctor or care team | Required by the team's safety rules |

## Results

${summary.map((s) => "- " + s).join("\n")}

Reading ease (Flesch, higher is easier): median ${[...rows].map((x) => x.r.ease).sort((a, b) => a - b)[Math.floor(n / 2)]}.

## Hardest 5 to read

| Patient | Grade | Words/sentence | Medical words left |
|---|---|---|---|
${worst.map((x) => `| ${x.id} | ${x.r.grade} | ${x.r.wordsPerSentence} | ${x.r.jargon.map((j) => j.term).join(", ") || "–"} |`).join("\n")}

## Example (${sample.id})

> ${sample.text}

Grade ${sample.r.grade} · ${sample.r.wordsPerSentence} words per sentence · safety ${sample.s.pass ? "passed" : "failed"}.

${safeFail.length ? `## Safety failures\n\n${safeFail.slice(0, 20).map((x) => `- ${x.id}: ${x.s.checks.filter((c) => !c.pass).map((c) => c.label + " — " + c.detail).join("; ")}`).join("\n")}\n` : ""}
## How to use this for the AI

When Rishi's endpoint produces answers, save them as \`[{"id": "PC0001", "text": "..."}]\` and run
\`node web/tests/check_explanations.mjs --ai that_file.json --report docs/testing/readability-report-ai.md\`.
The same rules run in the browser panel, which hides any answer that fails a safety check.
`;
  mkdirSync(dirname(resolve(reportPath)), { recursive: true });
  writeFileSync(reportPath, md);
  console.log(`Report written to ${reportPath}`);
}
process.exitCode = safeFail.length ? 1 : 0;
